//! `huddle-check-attribution [revision-range]`: fails when any commit in the history credits an
//! AI tool. GitHub lists every author, committer and `Co-authored-by` identity as a contributor,
//! so one stray trailer puts a bot on the repository page.

use std::ffi::OsStr;
use std::io::{self, Write};
use std::process::Command;

/// The identities AI coding tools commit or co-author as: their emails and bot accounts, not
/// people's names. Matched case-insensitively as substrings of the lowercased text.
const AI: &[&str] = &[
    "@anthropic.com",
    "claude-code",
    "cursoragent",
    "@cursor.com",
    "codex",
    "chatgpt",
    "@openai.com",
    "devin-ai",
    "(aider)",
    "gemini-code-assist",
    "google-labs-jules",
    "amazon-q-developer",
    "windsurf",
    "codeium",
    "tabnine",
    "sweep-ai",
];

const TRAILERS: &[&str] = &[
    "co-authored-by",
    "signed-off-by",
    "assisted-by",
    "generated-by",
    "created-by",
    "written-by",
    "claude-session",
];

const GENERATED: &[&str] = &[
    "generated with",
    "generated by",
    "claude.com/claude-code",
    "claude.ai/code",
];

const FORMAT: &str = "%H\u{1f}%an <%ae>\u{1f}%cn <%ce>\u{1f}%B\u{1e}";
const FIELD: char = '\u{1f}';
const RECORD: char = '\u{1e}';

/// `copilot` matches only as a standalone word, so a made-up word like "copilotish" stays clean.
fn has_standalone_word(hay_lower: &str, word: &str) -> bool {
    let is_word_char = |c: char| c.is_ascii_alphanumeric() || c == '_';
    let mut from = 0;
    while let Some(rel) = hay_lower[from..].find(word) {
        let start = from + rel;
        let end = start + word.len();
        let before = hay_lower[..start]
            .chars()
            .next_back()
            .is_none_or(|c| !is_word_char(c));
        let after = hay_lower[end..]
            .chars()
            .next()
            .is_none_or(|c| !is_word_char(c));
        if before && after {
            return true;
        }
        from = end;
    }
    false
}

fn credits_ai(text: &str) -> bool {
    let lower = text.to_lowercase();
    AI.iter().any(|marker| lower.contains(marker)) || has_standalone_word(&lower, "copilot")
}

fn is_trailer(line: &str, names: &[&str]) -> bool {
    let lower = line.trim().to_lowercase();
    names.iter().any(|name| {
        lower
            .strip_prefix(name)
            .is_some_and(|rest| rest.trim_start().starts_with(':'))
    })
}

fn is_generated(line: &str) -> bool {
    let lower = line.to_lowercase();
    lower.contains('\u{1f916}') || GENERATED.iter().any(|marker| lower.contains(marker))
}

/// The problem lines for one `git log` output: one per author, committer or body line that
/// credits an AI tool.
fn problems(history: &str) -> Vec<String> {
    let mut found = Vec::new();
    for entry in history.split(RECORD) {
        let record = entry.trim_start_matches('\n');
        if record.is_empty() {
            continue;
        }
        let mut parts = record.splitn(4, FIELD);
        let (Some(sha), Some(author), Some(committer), Some(body)) =
            (parts.next(), parts.next(), parts.next(), parts.next())
        else {
            continue;
        };
        let at: String = sha.chars().take(7).collect();
        if credits_ai(author) {
            found.push(format!("{at} author {author}"));
        }
        if credits_ai(committer) {
            found.push(format!("{at} committer {committer}"));
        }
        for line in body.split('\n') {
            let trimmed = line.trim();
            if is_trailer(trimmed, &["co-authored-by"]) {
                // Every co-author trailer fails: GitHub shows each one as a contributor.
                found.push(format!("{at} co-author: {trimmed}"));
            } else if is_trailer(trimmed, TRAILERS) && credits_ai(line) {
                found.push(format!("{at} trailer: {trimmed}"));
            } else if is_generated(line) {
                found.push(format!("{at} attribution line: {trimmed}"));
            }
        }
    }
    found
}

fn run(range: &OsStr, out: &mut impl Write, err: &mut impl Write) -> i32 {
    let format = format!("--format={FORMAT}");
    let output = match Command::new("git")
        .args(["log", "--no-color", &format])
        .arg(range)
        .output()
    {
        Ok(output) if output.status.success() => output,
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            let _ = writeln!(err, "check-attribution: git log failed: {}", stderr.trim());
            return 1;
        }
        Err(error) => {
            let _ = writeln!(err, "check-attribution: git log failed: {error}");
            return 1;
        }
    };
    let history = String::from_utf8_lossy(&output.stdout);
    let found = problems(&history);
    if found.is_empty() {
        let _ = writeln!(out, "check-attribution: no AI attribution in the history");
        return 0;
    }
    let _ = writeln!(
        err,
        "check-attribution: commits credit an AI tool (see AGENTS.md, Commits):"
    );
    for problem in &found {
        let _ = writeln!(err, "  {problem}");
    }
    1
}

fn main() {
    let mut args = std::env::args_os();
    args.next();
    let range = args
        .next()
        .unwrap_or_else(|| OsStr::new("HEAD").to_os_string());
    let code = run(&range, &mut io::stdout().lock(), &mut io::stderr().lock());
    std::process::exit(code);
}
